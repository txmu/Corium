#!/usr/bin/env python3
"""Generate exact theorem declarations; Lean remains the proof checker."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
MODULES = ('Models', 'Implementation', 'Refinements', 'Consensus', 'StateMachine',
           'Governance', 'OpenCI', 'Privacy', 'ContentFabric', 'DNA', 'Cooperatives', 'Bootstrap')


def inventory():
    actual = {p.stem for p in ROOT.glob('*.lean')}
    if actual != set(MODULES):
        raise ValueError(f'Formal module list drift: {actual.symmetric_difference(MODULES)}')
    output = ['# Exact Lean theorem declarations\n',
              'Generated by `python3 formal/theorem_inventory.py --write`. '
              'Declarations include premises; definitions and proof bodies remain in the linked source. '
              'This inventory does not assert production refinement or independent audit.\n']
    count = 0
    for module in MODULES:
        source = (ROOT / f'{module}.lean').read_text()
        namespaces = re.findall(r'^namespace (\S+)', source, re.M)
        if len(namespaces) != 1:
            raise ValueError(f'Review namespace handling for {module}')
        namespace = namespaces[0]
        declarations = list(re.finditer(r'^theorem ([A-Za-z_][A-Za-z_0-9]*)\b', source, re.M))
        output.append(f'## [{module}.lean]({module}.lean) — {len(declarations)} declarations\n')
        for declaration in declarations:
            count += 1
            end = source.index(':=', declaration.end())
            signature = source[declaration.start():end].rstrip()
            output.append(f'`{namespace}.{declaration[1]}`\n\n```lean\n{signature}\n```\n')
    output.insert(2, f'Total: **{count}** theorem declarations across **{len(MODULES)}** modules.\n')
    return '\n'.join(output)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--modules', action='store_true')
    args = parser.parse_args()
    if args.modules:
        inventory()  # Fail if a new module would be silently omitted.
        print('\n'.join(MODULES))
        return
    expected = inventory()
    path = ROOT / 'THEOREMS.md'
    if args.write:
        path.write_text(expected)
    elif not path.exists() or path.read_text() != expected:
        raise SystemExit('Theorem inventory drift: review declarations and regenerate formal/THEOREMS.md')
    print('Exact theorem inventory matches source')


if __name__ == '__main__':
    main()
